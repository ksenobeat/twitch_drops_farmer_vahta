"""База игр Twitch: категории с обложками, собранные заранее.

Собирает её `tools/games.py` — обходит Helix и складывает `games.json.gz`
(сегодня это 3941 игра и 79 килобайт). Здесь только приёмка: прочитать и влить
в таблицу `game`, ту же, в которую клиент и так пишет игры из кампаний.

Зачем она вообще: чтобы человек, добавляя игру, видел подсказки с первой буквы,
и чтобы можно было завести игру, у которой кампании сейчас нет, — она подхватится
сама, когда дропсы появятся.

Полного каталога Twitch тут нет и быть не может: `games/top` отдаёт только тех,
у кого сейчас есть эфир, а всё остальное Twitch показывает лишь поиском.
Ходить за редкой игрой в сеть по мере ввода мы не стали: у Helix для этого нужен
секрет приложения, а секрет в клиенте — это секрет у всех; приватный GQL умеет
искать, но его персистентный запрос пришлось бы добывать с живого сайта и потом
чинить каждый раз, когда Twitch его сменит. Игра не из списка добавляется как
и раньше — по точному названию (`DirectoryGameRedirect`), и это написано прямо
под полем ввода.

Три решения:

- **Вливаем при каждом запуске, без учёта версий.** Соблазн завести отметку
  «эту базу уже вливали» есть всегда, но она стоила бы таблицы, миграции и
  вопроса «а если файл подменили, а версия та же». Влить заново — три десятка
  миллисекунд на четыре тысячи строк, и это дешевле, чем помнить.
- **Своё не затираем.** Название и обложка, которые клиент узнал из живой
  кампании, остаются как есть: их он видел своими глазами, а каталог — это
  слепок, снятый неизвестно когда. Каталог только добавляет игры и заполняет
  пустую обложку.
- **Шаблон превращаем в адрес здесь.** В файле обложка лежит как
  `…/263490_IGDB-{width}x{height}.jpg` — так её отдаёт Twitch, и так она годится
  на любой размер. Но вся остальная «Вахта» ждёт от `box_art` готовый адрес,
  поэтому подставляем 120x160 — тот же размер, что приезжает с кампаниями.
"""

from __future__ import annotations

import gzip
import json
import logging
from pathlib import Path

from .paths import DATA_DIR, resources

log = logging.getLogger("vahta")

ИМЯ = "games.json.gz"


def файл() -> Path | None:
    """Где лежит база. Скачанная из релизов важнее приехавшей со сборкой.

    Порядок именно такой, потому что сборка обновляется реже базы: между двумя
    релизами игр прибавляется, а инсталлер тот же. Нет ни той, ни другой —
    не беда: подсказки будут только по играм, которые клиент видел сам.
    """
    for где in (DATA_DIR / ИМЯ, resources() / "vahta" / ИМЯ):
        if где.is_file():
            return где
    return None


def адрес_обложки(шаблон: str) -> str:
    """Шаблон Twitch → готовый адрес. Размер тот же, что у кампаний."""
    return шаблон.replace("{width}", "120").replace("{height}", "160")


def собрана(path: Path | None = None) -> str:
    """Дата сборки базы, которая лежит у нас. Пусто — базы нет или она битая.

    Читается отдельно от заливки и лишним заходом в gzip: восемьдесят
    килобайт распаковываются за миллисекунду, а сцеплять «влей» и «скажи дату»
    в один вызов значило бы, что одно без другого не спросить.
    """
    path = path or файл()
    if path is None:
        return ""
    try:
        данные = json.loads(gzip.decompress(path.read_bytes()).decode("utf8"))
        return str(данные.get("built") or "")
    except Exception:
        return ""


async def обновить(service) -> bool:
    """Забрать из релизов GitHub базу свежее нашей. True — забрали и влили.

    Даты сравниваются строками: `2026-08-01` больше `2026-07-31` по алфавиту,
    потому что ISO для того и придуман. Хэш и скачивание — те же, что у
    инсталлера: там уже решено, как качать во временное имя и как поступать,
    когда не сошлось.

    GitHub молчит, файла нет, хэш не сошёлся — ничего не происходит, и это
    нормальная работа: подсказки останутся по той базе, что приехала со сборкой.
    """
    from .update import fetch  # там же, где качается инсталлер

    свежая = service.games_built
    if not свежая or not service.games_url or not service.games_sha256:
        return False
    if свежая <= (service.games_have or ""):
        return False
    log.info("Качаю базу игр от %s", свежая)
    got = await fetch(service.games_url, service.games_sha256,
                      DATA_DIR / ИМЯ, что="База игр")
    if got is None:
        return False
    влить(service.store, got)
    service.games_have = собрана(got)
    return True


def влить(store, path: Path | None = None) -> int:
    """Влить базу в таблицу `game`. Возвращает, сколько игр прибавилось.

    Ничего не ломает, если файла нет или он битый: база игр — удобство, а не
    условие работы, и запуск из-за неё падать не должен.
    """
    path = path or файл()
    if path is None:
        return 0
    try:
        данные = json.loads(gzip.decompress(path.read_bytes()).decode("utf8"))
        строки = [
            (g["id"], g["name"], адрес_обложки(g.get("art") or ""))
            for g in данные.get("games", [])
        ]
    except Exception as exc:
        log.warning("База игр не прочиталась (%s): %s: %s",
                    path.name, type(exc).__name__, exc)
        return 0
    added = store.add_games(строки)
    log.info("База игр от %s: %d игр, новых %d",
             данные.get("built", "?"), len(строки), added)
    return added
